CREATE TABLE notification_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT,
    consumer_email VARCHAR(255) NOT NULL,
    content VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    attempts INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(255)
);

CREATE INDEX idx_notification_tasks_order_id
    ON notification_tasks (order_id);

CREATE INDEX idx_notification_tasks_status_created_at
    ON notification_tasks (status, created_at);